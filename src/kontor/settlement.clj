(defn- ref-id [x] (if (map? x) (:db/id x) x))

(defn- world-number
  "The number the numbering rendered for entry `t` in the world, or nil when
   its external-id is the caller's own."
  [db {:kontor.transaction/keys [external-id sequence-number journal effective-date]}]
  (when (and external-id sequence-number)
    (let [cfg (numbering/journal-config db (ref-id journal))]
      (when (= external-id (numbering/render cfg sequence-number effective-date))
        external-id))))

(defn- intent
  [world-db e]
  (let [t (d/pull world-db '[* {:kontor.transaction/posted-by [:kontor.actor/uid]}] e)
        rendered (world-number world-db t)
        caller-id (when-not rendered (:kontor.transaction/external-id t))
        reverses (ref-id (:kontor.transaction/reverses t))
        entry (cond-> {:journal (ref-id (:kontor.transaction/journal t))
                       :effective-date (:kontor.transaction/effective-date t)
                       :postings (book/entry-postings world-db e)}
                (:kontor.transaction/narration t) (assoc :narration (:kontor.transaction/narration t))
                (:kontor.transaction/partner t) (assoc :partner (ref-id (:kontor.transaction/partner t)))
                caller-id (assoc :external-id caller-id)
                (seq (:kontor.transaction/settles t))
                (assoc :settles (mapv ref-id (:kontor.transaction/settles t))))
        origin (:kontor.transaction/origin-id t)]
    {:intent/id origin
     :kind :entry
     :footprint (cond-> #{[:origin origin]}
                  caller-id (conj [:external-id caller-id])
                  reverses (conj [:reverses reverses]))
     :effective-date (:kontor.transaction/effective-date t)
     :entry entry
     :reverses reverses
     :actor (get-in t [:kontor.transaction/posted-by :kontor.actor/uid])
     :world-number rendered
     ::world-eid e}))

(defn- plain
  "A pulled entity as data for re-creation: refs as eids, without the
   attributes in `drop`."
  [m drop]
  (into {} (keep (fn [[k v]]
                   (when-not (contains? drop k)
                     [k (cond (map? v) (:db/id v)
                              (and (coll? v) (map? (first v))) (mapv :db/id v)
                              :else v)])))
        (dissoc m :db/id)))

(defn- invoice-intent
  [world-db e]
  (let [inv (d/pull world-db '[* {:kontor.invoice/lines [*]}] e)
        ext (:kontor.invoice/external-id inv)
        origin (some->> (:kontor.invoice/transaction inv) ref-id
                        (d/entity world-db) :kontor.transaction/origin-id)]
    {:intent/id (str "invoice:" ext)
     :kind :invoice
     :footprint #{[:invoice ext]}
     :effective-date (:kontor.invoice/issue-date inv)
     :invoice (plain inv #{:kontor.invoice/lines :kontor.invoice/transaction
                           :kontor.invoice/status :kontor.invoice/number})
     :lines (mapv #(plain % #{:kontor.invoice-line/invoice})
                  (sort-by :kontor.invoice-line/sequence (:kontor.invoice/lines inv)))
     ;; a paid one replays as sent: its match re-derives the rest
     :status (if (= :paid (:kontor.invoice/status inv)) :sent (:kontor.invoice/status inv))
     :transaction-origin origin
     :world-number (:kontor.invoice/number inv)}))

(defn- ref-values [m] (filter integer? (mapcat #(if (coll? %) % [%]) (vals m))))

(defn- import-intent
  "A bank line the world imported: re-imported in the parent, unmatched —
   a match of it is replayed as its own intent."
  [world-db e]
  (let [line (d/pull world-db '[*] e)]
    {:intent/id (str "bank-line:" (:kontor.bank-line/external-id line))
     :kind :import
     :footprint #{}
     :effective-date (:kontor.bank-line/date line)
     :line (assoc (plain line #{:kontor.bank-line/status :kontor.bank-line/reconciled-at
                                :kontor.bank-line/posting})
                  :kontor.bank-line/status :unmatched)}))

(defn- match-intent
  "A bank line the world matched, as the match decision itself: the replay
   re-runs `kontor.banking.reconciliation/commit-match-tx-data` in the
   parent, which re-derives the payment, its applications and the settled
   invoices' statuses against the parent's state."
  [base-db world-db e]
  (let [line (d/pull world-db [:kontor.bank-line/external-id :kontor.bank-line/date
                               {:kontor.bank-line/source-account [:db/id]}
                               {:kontor.bank-line/posting [{:kontor.posting/transaction [:db/id]}]}]
                     e)
        pay (get-in line [:kontor.bank-line/posting :kontor.posting/transaction :db/id])
        t (d/pull world-db '[*] pay)
        bank (get-in line [:kontor.bank-line/source-account :db/id])
        contra (some (fn [p] (let [a (ref-id (:account p))] (when (not= a bank) a)))
                     (book/entry-postings world-db pay))
        applied-by (d/q '[:find ?u . :in $ ?p
                          :where [?a :kontor.payment-application/payment ?p]
                          [?a :kontor.payment-application/applied-by-uid ?u]]
                        world-db pay)
        settles (mapv (fn [s]
                        (let [s (ref-id s)]
                          (if (existed? base-db s)
                            {:eid s}
                            {:origin (:kontor.transaction/origin-id (d/entity world-db s))})))
                      (:kontor.transaction/settles t))]
    {::settled (mapv ref-id (:kontor.transaction/settles t))
     :intent/id (str "match:" (:kontor.bank-line/external-id line))
     :kind :match
     :footprint #{[:bank-line (:kontor.bank-line/external-id line)]
                  [:external-id (:kontor.transaction/external-id t)]}
     :effective-date (:kontor.bank-line/date line)
     :line-id (:kontor.bank-line/external-id line)
     :payment-id (:kontor.transaction/external-id t)
     :payment-origin (:kontor.transaction/origin-id t)
     :journal (ref-id (:kontor.transaction/journal t))
     :contra contra
     :settles settles
     :applied-by applied-by
     ::payment-eid pay}))

(declare referenced-entry-eids)

(defn- referenced-eids
  "Every entity id an intent refers to."
  [{:keys [kind entry reverses invoice lines line journal contra applied-by settles]}]
  (case kind
    :invoice (distinct (concat (remove #{(:kontor.invoice/issue-date invoice)} (ref-values invoice))
                               (mapcat ref-values lines)))
    :import (ref-values (dissoc line :kontor.bank-line/amount :kontor.bank-line/date
                                :kontor.bank-line/value-date))
    :match (remove nil? (concat [journal contra applied-by] (keep :eid settles)))
    (referenced-entry-eids entry reverses)))

(defn- referenced-entry-eids
  [entry reverses]
  (->> (concat [(:journal entry) (:partner entry) reverses]
               (:settles entry)
               (mapcat (fn [p] (concat [(:account p) (:commodity p) (:partner p)
                                        (:entity p) (:ledger p)]
                                       (keep :plan (:analytic-distributions p))
                                       (keep :account (:analytic-distributions p))))
                       (:postings entry)))
       (filter integer?)
       distinct))

(defn extract
  "The world's net effect since its base, as intents (see the namespace):
   every entry it posted, except an entry it reversed itself — which is
   dropped together with its reversal. Throws `::unsupported` for anything
   else it changed, and `::new-reference` when an entry refers to an entity
   the world created (this slice replays against the base's entities)."
  [base-db world-db]
  (let [grouped (check-changes! base-db world-db (changed-entities base-db world-db))
        lines (ids-of grouped :bank-lines)
        matched (filterv (fn [e]
                           (and (= :reconciled (:kontor.bank-line/status (d/entity world-db e)))
                                (not= :reconciled (:kontor.bank-line/status (d/entity base-db e)))))
                         lines)
        matches (mapv #(match-intent base-db world-db %) matched)
        payments (set (map ::payment-eid matches))
        settled-invoices (set (d/q '[:find [?i ...] :in $ [?t ...]
                                     :where [?i :kontor.invoice/transaction ?t]]
                                   world-db (vec (mapcat ::settled matches))))
        _ (doseq [i (ids-of grouped :invoices)
                  :when (and (= :paid (:kontor.invoice/status (d/entity world-db i)))
                             (not (contains? settled-invoices i)))]
            (unsupported! "holds a paid invoice no match of it settles" {:entity i}))
        _ (doseq [i (ids-of grouped :invoice-statuses)
                  :when (not (contains? settled-invoices i))]
            (unsupported! "changed the status of an invoice no match of it settles" {:entity i}))
        txs (remove payments (ids-of grouped :transactions))
        intents (mapv #(intent world-db %) txs)
        in-world (set txs)
        self-reversed (set (mapcat (fn [{:keys [reverses] :as i}]
                                     (when (contains? in-world reverses)
                                       [reverses (::world-eid i)]))
                                   intents))
        kept (concat (remove #(contains? self-reversed (::world-eid %)) intents)
                     (map #(invoice-intent world-db %) (ids-of grouped :invoices))
                     (map #(import-intent world-db %) (remove #(existed? base-db %) lines))
                     matches)]
    (doseq [i kept
            e (referenced-eids i)
            :when (not (existed? base-db e))]
      (throw (ex-info "kontor.settlement: an entry refers to an entity the world created"
                      {:type ::new-reference :entity e :intent (:intent/id i)})))
    (vec (sort-by (juxt :effective-date #(str (:intent/id %))) kept))))

(defn parent-claims
  "The footprint keys the parent claimed since `base-db`: its own entries'
   origins, caller ids and the base entries it reversed. Unlike [[extract]]
   this reads whatever the parent did and refuses nothing."
  [base-db parent-db]
  (let [since (:max-tx base-db)
        txs (d/q '[:find [?t ...] :in $ ?since
                   :where [?t :kontor.transaction/posted-at _ ?tx] [(> ?tx ?since)]]
                 parent-db since)
        invoices (d/q '[:find [?x ...] :in $ ?since
                        :where [?i :kontor.invoice/external-id ?x ?tx] [(> ?tx ?since)]]
                      parent-db since)]
    (into (into (set (map (fn [x] [:invoice x]) invoices))
                (map (fn [x] [:bank-line x]))
                (d/q '[:find [?x ...] :in $ ?since
                       :where [?l :kontor.bank-line/status :reconciled ?tx] [(> ?tx ?since)]
                       [?l :kontor.bank-line/external-id ?x]]
                     parent-db since))
          (mapcat (fn [e]
                    (let [t (d/pull parent-db '[*] e)
                          caller-id (when-not (world-number parent-db t)
                                      (:kontor.transaction/external-id t))]
                      (cond-> []
                        (:kontor.transaction/origin-id t) (conj [:origin (:kontor.transaction/origin-id t)])
                        caller-id (conj [:external-id caller-id])
                        (:kontor.transaction/reverses t)
                        (conj [:reverses (ref-id (:kontor.transaction/reverses t))])))))
          txs)))

