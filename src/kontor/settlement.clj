(ns kontor.settlement
  "A book that lived in a speculative world settles into its parent by
   replay, never by datom merge (ADR-172).

   A world — a branch of the book an agent works in — is an autonomous book:
   it posts, numbers and reverses as the root does. When the parent takes it
   in, [[extract]] reads the world's NET effect since its base as intents,
   [[parent-claims]] what the parent did meanwhile, and [[stamp!]] re-posts
   the intents through the gate in the parent, which allocates fresh gapless
   numbers. Conflicts between worlds, or between a world and its parent, are
   decided by the caller (footprints), never by picking datoms.

   An intent:

     {:intent/id      origin uuid (`:kontor.transaction/origin-id`)
      :footprint      #{[:origin id] [:external-id caller-id] [:reverses eid] …}
      :effective-date inst
      :entry          `kontor.book` entry options that re-create the entry
      :reverses       eid of a base entry it reverses, or nil
      :actor          uid of who sealed it, or nil
      :world-number   the number it carried in the world, or nil}

   Replayed: posted journal entries (any `kontor.book` verb), reversals, and
   invoices the world created — as drafts, or sent, in which case the replay
   links them to their replayed posting and the gate gives them the parent's
   gapless `:kontor.invoice/number` (an invoice intent's footprint is
   `[:invoice external-id]`). Anything else a world changed — a draft entry,
   a new partner or account, an invoice paid or cancelled, a period close —
   is refused by [[extract]] with the entities named: silently carrying it
   over as datoms is exactly what this namespace exists to prevent."
  (:require [datahike.api :as d]
            [kontor.book :as book]
            [kontor.book.build :as build]
            [kontor.banking.reconciliation :as recon]
            [kontor.document.invoice :as invoice]
            [kontor.workflow.status-machine :as sm]
            [kontor.gate :as gate]
            [kontor.numbering :as numbering]
            [kontor.posting.build :as posting-build]))

;; ============================================================================
;; What a world changed
;; ============================================================================

(defn- world-datoms
  "Datoms `world-db` holds that `base-db` did not: those of transactions
   after the base's last one (a branch continues the base's history)."
  [base-db world-db]
  (let [since (:max-tx base-db)]
    (filter #(> (:tx %) since) (d/datoms world-db :eavt))))

(def ^:private carried-transaction-attrs
  "Transaction attributes a replay re-creates from the entry, or that the
   gate regenerates in the parent."
  #{:kontor.transaction/journal :kontor.transaction/effective-date
    :kontor.transaction/narration :kontor.transaction/partner
    :kontor.transaction/external-id :kontor.transaction/settles
    :kontor.transaction/reverses :kontor.transaction/origin-id
    ;; regenerated by the seal and the gate
    :kontor.transaction/state :kontor.transaction/posted-at
    :kontor.transaction/posted-by :kontor.transaction/sequence-number
    :kontor.transaction/sequence-key
    :kontor.audit/create-uid :kontor.audit/write-uid})

(def ^:private carried-posting-attrs
  "Posting attributes `kontor.book/entry-postings` re-creates."
  #{:kontor.posting/transaction :kontor.posting/posted-at
    :kontor.posting/account :kontor.posting/amount :kontor.posting/commodity
    :kontor.posting/partner :kontor.posting/entity :kontor.posting/ledger
    :kontor.posting/narration :kontor.posting/display-type
    :kontor.posting/period-tag :kontor.posting/dimensions
    :kontor.posting/analytic-distributions
    :kontor.audit/create-uid :kontor.audit/write-uid})

(defn- valid-time-attr? [a] (= "db.valid" (namespace a)))

(defn- entity-kind
  "What entity `e` is, from the attributes it has in `db`."
  [db e]
  (let [attrs (set (map :a (d/datoms db :eavt e)))
        has (fn [ns] (some #(= ns (namespace %)) attrs))]
    (cond
      (contains? attrs :kontor.transaction/journal) :transaction
      (contains? attrs :kontor.invoice/external-id) :invoice
      (contains? attrs :kontor.bank-line/external-id) :bank-line
      (has "kontor.payment-application") :payment-application
      (has "kontor.invoice-line") :invoice-line
      (has "kontor.status-history") :status-history
      (contains? attrs :kontor.posting/transaction) :posting
      (has "kontor.posting-dimension") :posting-part
      (has "kontor.analytic-distribution") :posting-part
      (has "kontor.actor") :actor
      (contains? attrs :kontor.journal/code) :journal
      :else :other)))

(defn- existed? [db e] (boolean (seq (d/datoms db :eavt e))))

(defn- unsupported! [what details]
  (throw (ex-info (str "kontor.settlement: the world " what
                       " — this settlement cannot replay it, and carrying it"
                       " over as datoms would bypass the gate (ADR-172)")
                  (merge {:type ::unsupported} details))))

(defn- changed-entities
  "{eid #{attr}} of what the world changed, tx entities left out."
  [base-db world-db]
  (reduce (fn [m {:keys [e a tx]}]
            (if (or (= e tx) (= "db" (namespace a)))
              m
              (update m e (fnil conj #{}) a)))
          {}
          (world-datoms base-db world-db)))

(def ^:private replayed-invoice-statuses
  "`:paid` only when a replayed match settles it: the invoice replays as
   sent, and the match re-derives its status in the parent."
  #{:draft :sent :paid})

(defn- check-changes!
  "Refuse any change this slice does not replay. Returns {:transactions
   [eid] :invoices [eid]}, the new ones."
  [base-db world-db changes]
  (let [counter-attrs #{:kontor.journal/last-sequence :kontor.journal/last-sequence-key}]
    (group-by first
              (keep
               (fn [[e attrs]]
                 (let [kind (entity-kind world-db e)
                       new? (not (existed? base-db e))
                       attrs (remove valid-time-attr? attrs)]
                   (case kind
                     :transaction
                     (let [unknown (remove carried-transaction-attrs attrs)
                           t (d/pull world-db [:kontor.transaction/posted-at] e)]
                       (cond
                         (not new?) (unsupported! "changed an entry of its base" {:entity e :attrs (vec attrs)})
                         (seq unknown) (unsupported! "wrote transaction attributes a replay does not carry"
                                                     {:entity e :attrs (vec unknown)})
                         (not (:kontor.transaction/posted-at t)) (unsupported! "holds a draft entry" {:entity e})
                         :else [:transactions e]))
                     :invoice
                     (let [status (:kontor.invoice/status (d/pull world-db [:kontor.invoice/status] e))]
                       (cond
                         ;; a match settling it re-derives its status in the
                         ;; parent; anything else is checked in `extract`
                         (and (not new?) (every? #{:kontor.invoice/status} attrs))
                         [:invoice-statuses e]
                         (not new?) (unsupported! "changed an invoice of its base" {:entity e :attrs (vec attrs)})
                         (not (replayed-invoice-statuses status))
                         (unsupported! "holds an invoice in a status this settlement cannot replay"
                                       {:entity e :status status})
                         :else [:invoices e]))
                     :bank-line
                     (if (or new? (every? #{:kontor.bank-line/status :kontor.bank-line/reconciled-at
                                            :kontor.bank-line/posting}
                                          attrs))
                       [:bank-lines e]
                       (unsupported! "changed a bank line beyond matching it" {:entity e :attrs (vec attrs)}))
                     ;; regenerated when the match is replayed
                     :payment-application
                     (when-not new? (unsupported! "changed a payment application" {:entity e}))
                     :invoice-line (when-not new? (unsupported! "changed an invoice line of its base" {:entity e :attrs (vec attrs)}))
            ;; regenerated by the replay's own status changes
                     :status-history (when-not new? (unsupported! "changed a status history row" {:entity e}))
                     :posting
                     (let [unknown (remove carried-posting-attrs attrs)]
                       (when (or (not new?) (seq unknown))
                         (unsupported! "wrote posting attributes a replay does not carry"
                                       {:entity e :attrs (vec (if new? unknown attrs))}))
                       nil)
                     (:posting-part :actor) (when-not new? (unsupported! "changed an existing entity" {:entity e :kind kind :attrs (vec attrs)}))
                     :journal (when (seq (remove counter-attrs attrs))
                                (unsupported! "changed a journal" {:entity e :attrs (vec attrs)}))
                     (unsupported! "changed an entity of a kind it cannot replay"
                                   {:entity e :kind kind :attrs (vec attrs)}))))
               changes))))

(defn- ids-of [grouped k] (mapv second (get grouped k)))

